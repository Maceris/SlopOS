/*
 * setjmp.c, SlopOS's libc (decisions/0201, 20l): setjmp and longjmp, in assembly for each architecture, as no C can
 * keep its own registers. setjmp keeps the callee-saved registers (the carrier register Hemera reserves is one, which
 * C keeps as any other), the stack pointer, the return address, and the shadow stack's pointer as it will be once
 * setjmp has returned: x86-64's CET shadow stack (rdsspq, 0 without one), AArch64's Guarded Control Stack (GCSPR_EL0
 * where CHKFEAT says the thread has one) and RISC-V's Zicfiss (ssrdp, 0 without one). longjmp pops the shadow stack
 * back to that, as Hemera's fibers do when they switch (incsspq, GCSPOPM, or ssp written), puts the registers back,
 * and jumps to the return address with its value, 1 for 0. Their instructions for the shadow stacks are written as
 * bytes or generic encodings where an assembler needs a feature for them, and do nothing without one.
 *
 * jmp_buf's words: x86-64 rbx rbp r12 r13 r14 r15 rsp rip ssp; AArch64 x19-x28, x29, x30, sp, d8-d15, GCSPR; RISC-V
 * ra, sp, s0-s11, fs0-fs11, ssp.
 */
#include <setjmp.h>

#if defined(__x86_64__)
__asm__(".text\n"
        ".globl setjmp\n"
        ".type setjmp, @function\n"
        ".p2align 4\n"
        "setjmp:\n"
        "    endbr64\n"
        "    movq %rbx, 0(%rdi)\n"
        "    movq %rbp, 8(%rdi)\n"
        "    movq %r12, 16(%rdi)\n"
        "    movq %r13, 24(%rdi)\n"
        "    movq %r14, 32(%rdi)\n"
        "    movq %r15, 40(%rdi)\n"
        "    leaq 8(%rsp), %rdx\n"
        "    movq %rdx, 48(%rdi)\n"
        "    movq (%rsp), %rdx\n"
        "    movq %rdx, 56(%rdi)\n"
        /* rdsspq %rax, 0 without a shadow stack; once setjmp's returned, its own entry's popped */
        "    xorl %eax, %eax\n"
        "    .byte 0xf3, 0x48, 0x0f, 0x1e, 0xc8\n"
        "    testq %rax, %rax\n"
        "    jz 1f\n"
        "    addq $8, %rax\n"
        "1:  movq %rax, 64(%rdi)\n"
        "    xorl %eax, %eax\n"
        "    ret\n"
        ".size setjmp, . - setjmp\n"
        ".globl longjmp\n"
        ".type longjmp, @function\n"
        ".p2align 4\n"
        "longjmp:\n"
        "    endbr64\n"
        "    movq 64(%rdi), %rdx\n"
        "    testq %rdx, %rdx\n"
        "    jz 3f\n"
        /* rdsspq %rcx, then incsspq by the entries between, at most 255 at a time */
        "    xorl %ecx, %ecx\n"
        "    .byte 0xf3, 0x48, 0x0f, 0x1e, 0xc9\n"
        "    subq %rcx, %rdx\n"
        "    shrq $3, %rdx\n"
        "2:  testq %rdx, %rdx\n"
        "    jz 3f\n"
        "    movq %rdx, %rcx\n"
        "    cmpq $255, %rcx\n"
        "    jbe 4f\n"
        "    movl $255, %ecx\n"
        "4:  .byte 0xf3, 0x48, 0x0f, 0xae, 0xe9\n"
        "    subq %rcx, %rdx\n"
        "    jmp 2b\n"
        "3:  movl %esi, %eax\n"
        "    testl %eax, %eax\n"
        "    jnz 5f\n"
        "    movl $1, %eax\n"
        "5:  movq 0(%rdi), %rbx\n"
        "    movq 8(%rdi), %rbp\n"
        "    movq 16(%rdi), %r12\n"
        "    movq 24(%rdi), %r13\n"
        "    movq 32(%rdi), %r14\n"
        "    movq 40(%rdi), %r15\n"
        "    movq 48(%rdi), %rsp\n"
        "    jmpq *56(%rdi)\n"
        ".size longjmp, . - longjmp\n");
#elif defined(__aarch64__)
__asm__(".text\n"
        ".globl setjmp\n"
        ".type setjmp, %function\n"
        ".p2align 2\n"
        "setjmp:\n"
        "    bti c\n"
        "    stp x19, x20, [x0, #0]\n"
        "    stp x21, x22, [x0, #16]\n"
        "    stp x23, x24, [x0, #32]\n"
        "    stp x25, x26, [x0, #48]\n"
        "    stp x27, x28, [x0, #64]\n"
        "    stp x29, x30, [x0, #80]\n"
        "    mov x2, sp\n"
        "    str x2, [x0, #96]\n"
        "    stp d8, d9, [x0, #104]\n"
        "    stp d10, d11, [x0, #120]\n"
        "    stp d12, d13, [x0, #136]\n"
        "    stp d14, d15, [x0, #152]\n"
        /* CHKFEAT X16 clears bit 0 where the thread has a GCS; GCSPR_EL0 then, past setjmp's own entry */
        "    mov x16, #1\n"
        "    hint #40\n"
        "    mov x2, xzr\n"
        "    tbnz x16, #0, 1f\n"
        "    mrs x2, s3_3_c2_c5_1\n"
        "    add x2, x2, #8\n"
        "1:  str x2, [x0, #168]\n"
        "    mov w0, #0\n"
        "    ret\n"
        ".size setjmp, . - setjmp\n"
        ".globl longjmp\n"
        ".type longjmp, %function\n"
        ".p2align 2\n"
        "longjmp:\n"
        "    bti c\n"
        /* GCSPOPM until GCSPR_EL0 is back where setjmp left it */
        "    ldr x2, [x0, #168]\n"
        "    cbz x2, 3f\n"
        "2:  mrs x3, s3_3_c2_c5_1\n"
        "    cmp x3, x2\n"
        "    b.hs 3f\n"
        "    sysl x3, #3, c7, c7, #1\n"
        "    b 2b\n"
        "3:  ldp x19, x20, [x0, #0]\n"
        "    ldp x21, x22, [x0, #16]\n"
        "    ldp x23, x24, [x0, #32]\n"
        "    ldp x25, x26, [x0, #48]\n"
        "    ldp x27, x28, [x0, #64]\n"
        "    ldp x29, x30, [x0, #80]\n"
        "    ldr x2, [x0, #96]\n"
        "    mov sp, x2\n"
        "    ldp d8, d9, [x0, #104]\n"
        "    ldp d10, d11, [x0, #120]\n"
        "    ldp d12, d13, [x0, #136]\n"
        "    ldp d14, d15, [x0, #152]\n"
        "    cmp w1, #0\n"
        "    csinc w0, w1, wzr, ne\n"
        /* A branch, not a return, as the Guarded Control Stack's entry for setjmp's return is gone */
        "    br x30\n"
        ".size longjmp, . - longjmp\n");
#elif defined(__riscv)
__asm__(".text\n"
        ".globl setjmp\n"
        ".type setjmp, @function\n"
        ".p2align 2\n"
        "setjmp:\n"
        "    sd ra, 0(a0)\n"
        "    sd sp, 8(a0)\n"
        "    sd s0, 16(a0)\n"
        "    sd s1, 24(a0)\n"
        "    sd s2, 32(a0)\n"
        "    sd s3, 40(a0)\n"
        "    sd s4, 48(a0)\n"
        "    sd s5, 56(a0)\n"
        "    sd s6, 64(a0)\n"
        "    sd s7, 72(a0)\n"
        "    sd s8, 80(a0)\n"
        "    sd s9, 88(a0)\n"
        "    sd s10, 96(a0)\n"
        "    sd s11, 104(a0)\n"
        "    fsd fs0, 112(a0)\n"
        "    fsd fs1, 120(a0)\n"
        "    fsd fs2, 128(a0)\n"
        "    fsd fs3, 136(a0)\n"
        "    fsd fs4, 144(a0)\n"
        "    fsd fs5, 152(a0)\n"
        "    fsd fs6, 160(a0)\n"
        "    fsd fs7, 168(a0)\n"
        "    fsd fs8, 176(a0)\n"
        "    fsd fs9, 184(a0)\n"
        "    fsd fs10, 192(a0)\n"
        "    fsd fs11, 200(a0)\n"
        /*
         * ssrdp t0, 0 without a shadow stack; C's own frames push nothing on it. Its encoding, a Zimop instruction
         * (mop.r.28), as an assembler that holds Zicfiss experimental, as LLVM 23's does, won't take the mnemonic
         */
        "    .4byte 0xcdc042f3\n"
        "    sd t0, 208(a0)\n"
        "    li a0, 0\n"
        "    ret\n"
        ".size setjmp, . - setjmp\n"
        ".globl longjmp\n"
        ".type longjmp, @function\n"
        ".p2align 2\n"
        "longjmp:\n"
        "    ld t0, 208(a0)\n"
        "    beqz t0, 1f\n"
        /* ssp, CSR 0x11, back where setjmp read it */
        "    csrw 0x11, t0\n"
        "1:  ld ra, 0(a0)\n"
        "    ld sp, 8(a0)\n"
        "    ld s0, 16(a0)\n"
        "    ld s1, 24(a0)\n"
        "    ld s2, 32(a0)\n"
        "    ld s3, 40(a0)\n"
        "    ld s4, 48(a0)\n"
        "    ld s5, 56(a0)\n"
        "    ld s6, 64(a0)\n"
        "    ld s7, 72(a0)\n"
        "    ld s8, 80(a0)\n"
        "    ld s9, 88(a0)\n"
        "    ld s10, 96(a0)\n"
        "    ld s11, 104(a0)\n"
        "    fld fs0, 112(a0)\n"
        "    fld fs1, 120(a0)\n"
        "    fld fs2, 128(a0)\n"
        "    fld fs3, 136(a0)\n"
        "    fld fs4, 144(a0)\n"
        "    fld fs5, 152(a0)\n"
        "    fld fs6, 160(a0)\n"
        "    fld fs7, 168(a0)\n"
        "    fld fs8, 176(a0)\n"
        "    fld fs9, 184(a0)\n"
        "    fld fs10, 192(a0)\n"
        "    fld fs11, 200(a0)\n"
        "    seqz a0, a1\n"
        "    add a0, a0, a1\n"
        "    ret\n"
        ".size longjmp, . - longjmp\n");
#else
#error "setjmp and longjmp aren't written for this architecture"
#endif
