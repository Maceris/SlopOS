"""
Writes common_passwords.hsc from SecLists' 10,000 most common passwords (third_party/seclists): those of 8 characters
or more, since shorter ones are refused anyway, lowercased, deduplicated and sorted bytewise, for account_records.is_common's
binary search.

    python src/account_records/_generator/generate.py
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
SOURCE = ROOT / "third_party" / "seclists" / "10k-most-common.txt"
OUTPUT = HERE.parent / "common_passwords.hsc"
MIN_CHARACTERS = 8


def main():
    words = set()
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        word = line.strip().lower()
        if len(word) < MIN_CHARACTERS:
            continue
        if any(ord(c) < 0x20 or ord(c) > 0x7e or c in '"\\' for c in word):
            raise SystemExit(f"a password the table can't hold as it is: {word!r}")
        words.add(word)
    ordered = sorted(words, key=lambda word: word.encode("ascii"))
    lines = [
        "package account_records",
        "",
        "// Generated by _generator/generate.py from SecLists' 10k-most-common.txt (third_party/seclists); don't edit.",
        "",
        f"// The common passwords of {MIN_CHARACTERS} characters or more, lowercased, sorted bytewise.",
        "COMMON_PASSWORDS :: string.[",
    ]
    row = []
    width = 4
    for word in ordered:
        item = f'"{word}",'
        if row and width + len(item) + 1 > 120:
            lines.append("    " + " ".join(row))
            row = []
            width = 4
        row.append(item)
        width += len(item) + 1
    if row:
        lines.append("    " + " ".join(row))
    lines.append("]")
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(ordered)} passwords")


main()
